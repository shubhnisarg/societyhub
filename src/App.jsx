// ─── PETTY CASH TRACKER ───────────────────────────────────────────────────────
function PettyCashTracker({ token, members, currentUser, onSignIn }) {
  const [loading, setLoading] = useState(false);
  const [msg, setMsg] = useState(null);
  const [withdrawals, setWithdrawals] = useState([]);
  const [expenses, setExpenses] = useState([]);
  const [settlements, setSettlements] = useState([]);
  const [lastRefresh, setLastRefresh] = useState(null);

  // Detect columns dynamically from header row so old & new sheet formats both work
  const [wdAmtCol,   setWdAmtCol]   = useState(4);
  const [expAmtCol,  setExpAmtCol]  = useState(3);
  const [expModeCol, setExpModeCol] = useState(4);
  const [expSpentCol,setExpSpentCol]= useState(8);

  async function readSheetAll(sheetName, tok) {
    const url = `https://sheets.googleapis.com/v4/spreadsheets/${CONFIG.SPREADSHEET_ID}/values/${encodeURIComponent(sheetName + "!A1:Z500")}`;
    const resp = await fetch(url, { headers: { Authorization: `Bearer ${tok}` } });
    if (!resp.ok) throw new Error(await resp.text());
    const data = await resp.json();
    const all = data.values || [];
    return { headers: all[0] || [], rows: all.slice(1) };
  }

  function findCol(headers, ...names) {
    for (const name of names) {
      const idx = headers.findIndex(h => h.toLowerCase().includes(name.toLowerCase()));
      if (idx >= 0) return idx;
    }
    return -1;
  }

  async function loadData() {
    if (!token) { setMsg({ type: "info", text: "Sign in to see live data. Showing public view." }); return; }
    setLoading(true); setMsg(null);
    try {
      const [wdData, exData, stData] = await Promise.all([
        readSheetAll(SHEETS.WITHDRAWALS, token),
        readSheetAll(SHEETS.EXPENSES, token),
        readSheetAll(SHEETS.SETTLEMENTS, token).catch(() => ({ rows:[], headers:[] })),
      ]);

      // Auto-detect column positions from headers — handles both old and new sheet formats
      const _wdAmt   = findCol(wdData.headers,  "Amount");
      const _exAmt   = findCol(exData.headers,   "Amount");
      const _exMode  = findCol(exData.headers,   "Payment Mode", "Mode");
      const _exSpent = findCol(exData.headers,   "Spent By", "SpentBy");

      const wdAmt   = _wdAmt   >= 0 ? _wdAmt   : 4;
      const exAmt   = _exAmt   >= 0 ? _exAmt   : 3;
      const exMode  = _exMode  >= 0 ? _exMode  : 4;
      const exSpent = _exSpent >= 0 ? _exSpent : 8;

      setWdAmtCol(wdAmt);
      setExpAmtCol(exAmt);
      setExpModeCol(exMode);
      setExpSpentCol(exSpent);

      setWithdrawals(wdData.rows);
      setExpenses(exData.rows.filter(r => (r[exMode]||"").toLowerCase() === "cash"));
      setSettlements(stData.rows || []);

      setLastRefresh(new Date().toLocaleTimeString("en-IN"));
      setMsg({ type: "success", text: `Data refreshed. ` +
        `Withdrawal Amount col: ${wdAmt+1}, Expense Amount col: ${exAmt+1}, Spent By col: ${exSpent+1}.` });
    } catch (e) { setMsg({ type: "error", text: "Error loading data: " + e.message }); }
    setLoading(false);
  }

  useEffect(() => { loadData(); }, [token]);

  // ── Aggregations using dynamically detected column indices ──────────────
  const totalWithdrawn = withdrawals.reduce((s, r) => s + (parseFloat(r[wdAmtCol]) || 0), 0);
  const totalCashSpent = expenses.reduce((s, r) => s + (parseFloat(r[expAmtCol]) || 0), 0);
  const balance = totalWithdrawn - totalCashSpent;

  const wdByMember = {};
  withdrawals.forEach(r => {
    const name = r[1] || "Unknown";
    wdByMember[name] = (wdByMember[name] || 0) + (parseFloat(r[wdAmtCol]) || 0);
  });

  // Gross amount spent by each member
  const grossOwed = {};
  expenses.forEach(r => {
    const spentBy = r[expSpentCol] || "";
    const amount  = parseFloat(r[expAmtCol]) || 0;
    if (spentBy) grossOwed[spentBy] = (grossOwed[spentBy] || 0) + amount;
  });

  // Already settled per member — Settlements col[2]=Settled To, col[3]=Amount
  const totalSettled = {};
  settlements.forEach(r => {
    const member = r[2] || "";
    const amount = parseFloat(r[3]) || 0;
    if (member) totalSettled[member] = (totalSettled[member] || 0) + amount;
  });

  // Net pending dues = gross - settled
  const netLiabilities = {};
  Object.keys(grossOwed).forEach(name => {
    const net = (grossOwed[name] || 0) - (totalSettled[name] || 0);
    if (net > 0.001) netLiabilities[name] = net;
  });

  const allSpenders = Object.keys(grossOwed);
  const totalAlreadySettled = Object.values(totalSettled).reduce((s, v) => s + v, 0);

  const fmt = (n) => "₹" + Math.abs(n).toLocaleString("en-IN", { minimumFractionDigits: 2 });

  async function saveSummary() {
    if (!token) return;
    try {
      await appendToSheet(SHEETS.EXPENSES.replace("Expenses","Petty_Cash_Summary"),
        [new Date().toLocaleDateString("en-IN"), totalWithdrawn, totalCashSpent, balance, currentUser], token);
      setMsg({ type: "success", text: "Summary snapshot saved to Petty_Cash_Summary sheet." });
    } catch(e) { setMsg({ type: "error", text: e.message }); }
  }

  const SummaryCard = ({ icon, label, value, color }) => (
    <div style={{ background: "#fff", borderRadius: 12, padding: "18px 20px", boxShadow: "0 2px 8px rgba(26,77,92,0.08)", borderTop: `4px solid ${color}`, flex: 1, minWidth: 160 }}>
      <div style={{ fontSize: 22, marginBottom: 6 }}>{icon}</div>
      <div style={{ fontSize: 12, fontWeight: 600, color: "#7A9199", textTransform: "uppercase", letterSpacing: "0.4px", marginBottom: 4 }}>{label}</div>
      <div style={{ fontSize: 22, fontWeight: 700, color }}>{fmt(value)}</div>
    </div>
  );

  return (
    <div>
      <div className="page-title">⚖️ Petty Cash Tracker</div>
      <div className="page-desc">Reconciliation of cash withdrawals vs. expenses — balances and cross-member liabilities.</div>
      {!token && (
        <div className="alert alert-info" style={{ marginBottom:18 }}>
          <span>👁️</span>
          <div>
            <strong>Public View</strong> — You are viewing this as a guest.
            Data shown here is read from the society's Google Sheet.
            <span style={{ marginLeft:8, color:"#1A4D5C", cursor:"pointer", textDecoration:"underline", fontWeight:600 }}
              onClick={onSignIn}>Sign in</span> to access data entry modules.
          </div>
        </div>
      )}

      {msg && <Alert type={msg.type} onClose={() => setMsg(null)}>{msg.text}</Alert>}

      <div style={{ display: "flex", gap: 12, marginBottom: 20, flexWrap: "wrap" }}>
        <button className="btn btn-primary" onClick={loadData} disabled={loading}>
          {loading ? <><span className="spinner" /> Loading…</> : "🔄 Refresh Data"}
        </button>
        <button className="btn btn-secondary" onClick={saveSummary} disabled={!withdrawals.length}>
          💾 Save Snapshot to Sheet
        </button>
        {lastRefresh && <span style={{ alignSelf: "center", fontSize: 12, color: "#7A9199" }}>Last updated: {lastRefresh}</span>}
      </div>

      {/* Summary Cards */}
      <div style={{ display: "flex", gap: 14, marginBottom: 20, flexWrap: "wrap" }}>
        <SummaryCard icon="⬆️" label="Total Cash Withdrawn" value={totalWithdrawn} color="#1A4D5C" />
        <SummaryCard icon="⬇️" label="Total Cash Spent" value={totalCashSpent} color="#E8871A" />
        <SummaryCard icon="💰" label="Available Balance" value={balance} color={balance >= 0 ? "#1E7E44" : "#C0392B"} />
      </div>

      {/* Per-Member Breakdown */}
      {/* Bank Withdrawal Summary */}
      <div className="card">
        <div className="card-title">🏦 Bank Withdrawals — Who Withdrew</div>
        <div style={{fontSize:13, color:"#7A9199", marginBottom:14}}>Members who withdrew cash from bank in their name. All amounts handed to Treasurer.</div>
        {Object.keys(wdByMember).length === 0
          ? <Alert type="info">No withdrawal records found.</Alert>
          : <div style={{overflowX:"auto"}}>
              <table className="records-table">
                <thead><tr><th>Member (Cheque Issuer)</th><th>Total Withdrawn from Bank</th><th>Status</th></tr></thead>
                <tbody>
                  {Object.entries(wdByMember).map(([name, amt], i) => (
                    <tr key={i}>
                      <td><strong>{name}</strong></td>
                      <td><strong style={{color:"#1A4D5C"}}>₹{amt.toLocaleString("en-IN",{minimumFractionDigits:2})}</strong></td>
                      <td><span className="tag" style={{background:"#e8f4f8",color:"#1A4D5C"}}>Handed to Treasurer ✅</span></td>
                    </tr>
                  ))}
                  <tr style={{background:"#f0f9fc"}}>
                    <td><strong>Total Pool with Treasurer</strong></td>
                    <td><strong style={{color:"#1A4D5C",fontSize:15}}>₹{totalWithdrawn.toLocaleString("en-IN",{minimumFractionDigits:2})}</strong></td>
                    <td></td>
                  </tr>
                </tbody>
              </table>
            </div>
        }
      </div>

      {/* Treasurer Reimbursement Dues */}
      <div className="card">
        <div className="card-title">⚖️ Treasurer — Reimbursement Dues</div>
        <div style={{fontSize:13, color:"#7A9199", marginBottom:14}}>
          Net pending dues after deducting already settled amounts.
        </div>
        {allSpenders.length === 0
          ? <Alert type="success">No cash expenses recorded yet.</Alert>
          : <div style={{overflowX:"auto"}}>
              <table className="records-table">
                <thead>
                  <tr><th>Member</th><th>Total Spent</th><th>Already Settled</th><th>Net Pending</th><th>Status</th></tr>
                </thead>
                <tbody>
                  {allSpenders.map((name, i) => {
                    const gross   = grossOwed[name]    || 0;
                    const settled = totalSettled[name] || 0;
                    const net     = gross - settled;
                    return (
                      <tr key={i}>
                        <td><strong>{name}</strong></td>
                        <td style={{color:"#E8871A",fontWeight:600}}>₹{gross.toLocaleString("en-IN",{minimumFractionDigits:2})}</td>
                        <td style={{color:"#1E7E44",fontWeight:600}}>₹{settled.toLocaleString("en-IN",{minimumFractionDigits:2})}</td>
                        <td><strong style={{color: net > 0 ? "#C0392B" : "#1E7E44", fontSize:14}}>₹{net.toLocaleString("en-IN",{minimumFractionDigits:2})}</strong></td>
                        <td>
                          {net <= 0
                            ? <span className="tag" style={{background:"#D4EDDA",color:"#1E7E44"}}>✅ Settled</span>
                            : <span className="tag" style={{background:"#fff3e0",color:"#b45309"}}>Pending</span>
                          }
                        </td>
                      </tr>
                    );
                  })}
                  <tr style={{background:"#f7f4ef",fontWeight:600}}>
                    <td>Total</td>
                    <td style={{color:"#E8871A"}}>₹{totalCashSpent.toLocaleString("en-IN",{minimumFractionDigits:2})}</td>
                    <td style={{color:"#1E7E44"}}>₹{totalAlreadySettled.toLocaleString("en-IN",{minimumFractionDigits:2})}</td>
                    <td style={{color:"#C0392B",fontSize:15}}>₹{(totalCashSpent-totalAlreadySettled).toLocaleString("en-IN",{minimumFractionDigits:2})}</td>
                    <td></td>
                  </tr>
                </tbody>
              </table>
              {balance >= 0 && (
                <div style={{marginTop:14, background:"#D4EDDA", border:"1px solid #a8d5b5", borderRadius:8, padding:"10px 16px", fontSize:13, color:"#1E7E44"}}>
                  ✅ <strong>Remaining balance with Treasurer: ₹{balance.toLocaleString("en-IN",{minimumFractionDigits:2})}</strong> after all reimbursements.
                </div>
              )}
            </div>
        }
      </div>

      {/* Settlement Form — only for signed-in users */}
      {token && Object.keys(netLiabilities).length > 0 && (
        <SettlementForm
          members={Object.keys(netLiabilities)}
          netLiabilities={netLiabilities}
          token={token}
          currentUser={currentUser}
          onSettled={loadData}
        />
      )}
      {token && Object.keys(netLiabilities).length === 0 && allSpenders.length > 0 && (
        <div className="card">
          <div className="card-title">🤝 Record Settlement</div>
          <Alert type="success">All dues are fully settled — no pending reimbursements. ✅</Alert>
        </div>
      )}

      {/* Settlement History */}
      {settlements.length > 0 && (
        <div className="card">
          <div className="card-title">📋 Settlement History</div>
          <div style={{overflowX:"auto"}}>
            <table className="records-table">
              <thead><tr><th>Date</th><th>Settled By (Treasurer)</th><th>Settled To</th><th>Amount</th><th>Notes</th></tr></thead>
              <tbody>
                {settlements.map((r, i) => (
                  <tr key={i}>
                    <td>{r[4]}</td>
                    <td><strong>{r[1]}</strong></td>
                    <td><strong style={{color:"#1E7E44"}}>{r[2]}</strong></td>
                    <td><strong style={{color:"#1A4D5C"}}>₹{Number(r[3]).toLocaleString("en-IN",{minimumFractionDigits:2})}</strong></td>
                    <td style={{fontSize:12}}>{r[5]||"—"}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </div>
      )}

      {/* Withdrawal Detail Log */}
      <div className="card">
        <div className="card-title">📋 All Bank Withdrawals (Detail)</div>
        {withdrawals.length === 0
          ? <Alert type="info">No withdrawal records found.</Alert>
          : <div style={{overflowX:"auto"}}>
              <table className="records-table">
                <thead><tr><th>Date</th><th>Withdrawn By</th><th>Cheque No</th><th>Bank</th><th>Amount</th><th>Purpose</th></tr></thead>
                <tbody>
                  {withdrawals.map((r, i) => (
                    <tr key={i}>
                      <td>{r[5]}</td>
                      <td><strong>{r[1]}</strong></td>
                      <td><code style={{fontSize:11}}>{r[2]||"—"}</code></td>
                      <td style={{fontSize:12}}>{r[3]||"—"}</td>
                      <td><strong>₹{Number(r[4]).toLocaleString("en-IN")}</strong></td>
                      <td style={{fontSize:12}}>{r[6]||"—"}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
        }
      </div>

      {/* Cash Expense Detail Log */}
      <div className="card">
        <div className="card-title">📋 All Cash Expenses (Detail)</div>
        {expenses.length === 0
          ? <Alert type="info">No cash expense records found.</Alert>
          : <div style={{overflowX:"auto"}}>
              <table className="records-table">
                <thead><tr><th>Date</th><th>Category</th><th>Description</th><th>Amount</th><th>Spent By</th><th>Treasurer Owes</th></tr></thead>
                <tbody>
                  {expenses.map((r, i) => (
                    <tr key={i}>
                      <td>{r[0] ? r[0].split(",")[0] : "—"}</td>
                      <td style={{fontSize:12}}>{r[1]}</td>
                      <td>{r[2]}</td>
                      <td><strong>₹{Number(r[3]).toLocaleString("en-IN")}</strong></td>
                      <td><strong>{r[8]||"—"}</strong></td>
                      <td><span style={{color:"#C0392B",fontWeight:600}}>₹{Number(r[3]).toLocaleString("en-IN")}</span></td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
        }
      </div>
    </div>
  );
}

// ─── VIEW RECORDS ─────────────────────────────────────────────────────────────
function ViewRecords({ token, onSignIn }) {
  const [activeSheet, setActiveSheet] = useState("Cheque_Payments");
  const [rows, setRows] = useState([]);
  const [headers, setHeaders] = useState([]);
  const [loading, setLoading] = useState(false);
  const [msg, setMsg] = useState(null);
  const [search, setSearch] = useState("");
  const [dateFrom, setDateFrom] = useState("");
  const [dateTo, setDateTo] = useState("");

  const VIEWABLE = [
    { id: "Cheque_Payments",  label: "Cheque Payments",  icon: "🏦" },
    { id: "Cash_Withdrawals", label: "Cash Withdrawals", icon: "💵" },
    { id: "Expenses",         label: "Expenses",         icon: "📊" },
    { id: "Settlements",      label: "Settlements",      icon: "🤝" },
  ];

  async function loadRecords(sheet = activeSheet) {
    if (!token) { setMsg({ type: "error", text: "Please sign in first." }); return; }
    setLoading(true); setMsg(null); setRows([]); setHeaders([]);
    try {
      // Read header row
      const hUrl = `https://sheets.googleapis.com/v4/spreadsheets/${CONFIG.SPREADSHEET_ID}/values/${encodeURIComponent(sheet + "!A1:Z1")}`;
      const hResp = await fetch(hUrl, { headers: { Authorization: `Bearer ${token}` } });
      const hData = await hResp.json();
      const hdrs = (hData.values || [[]])[0] || [];
      setHeaders(hdrs);
      // Read data rows
      const data = await readSheet(sheet, token);
      setRows(data);
      if (data.length === 0) setMsg({ type: "info", text: "No records found in this sheet yet." });
    } catch (e) { setMsg({ type: "error", text: "Error: " + e.message }); }
    setLoading(false);
  }

  useEffect(() => { loadRecords(activeSheet); }, [activeSheet, token]);

  // Filter rows
  const filtered = rows.filter(r => {
    const rowText = r.join(" ").toLowerCase();
    const matchSearch = !search || rowText.includes(search.toLowerCase());
    // Date filter: col 0 is timestamp for Cheque/Expenses, col 3 is date for Withdrawals
    const dateCol = activeSheet === "Cash_Withdrawals" ? r[3] : r[0];
    const matchFrom = !dateFrom || (dateCol && dateCol >= dateFrom);
    const matchTo   = !dateTo   || (dateCol && dateCol <= dateTo + "z");
    return matchSearch && matchFrom && matchTo;
  });

  const totalAmount = filtered.reduce((s, r) => {
    const amtIdx = headers.findIndex(h => h.toLowerCase() === "amount");
    return s + (amtIdx >= 0 ? parseFloat(r[amtIdx]) || 0 : 0);
  }, 0);

  function downloadCSV() {
    const csvRows = [headers, ...filtered].map(r => r.map(c => `"${(c||"").replace(/"/g,'""')}"`).join(","));
    const blob = new Blob([csvRows.join("\n")], { type: "text/csv" });
    const a = document.createElement("a");
    a.href = URL.createObjectURL(blob);
    a.download = `${activeSheet}_${today()}.csv`;
    a.click();
  }

  return (
    <div>
      <div className="page-title">📁 View Records</div>
      <div className="page-desc">Browse, search, and filter all recorded data from the society's Google Sheets.</div>
      {!token && (
        <div className="alert alert-info" style={{ marginBottom:18 }}>
          <span>👁️</span>
          <div>
            <strong>Public View</strong> — You are viewing this as a guest. All records are read-only.
            <span style={{ marginLeft:8, color:"#1A4D5C", cursor:"pointer", textDecoration:"underline", fontWeight:600 }}
              onClick={onSignIn}>Sign in</span> to access data entry modules.
          </div>
        </div>
      )}

      {msg && <Alert type={msg.type} onClose={() => setMsg(null)}>{msg.text}</Alert>}

      {/* Sheet Selector */}
      <div style={{ display: "flex", gap: 10, marginBottom: 20, flexWrap: "wrap" }}>
        {VIEWABLE.map(s => (
          <button key={s.id}
            className={`btn ${activeSheet === s.id ? "btn-primary" : "btn-secondary"}`}
            onClick={() => { setActiveSheet(s.id); setSearch(""); setDateFrom(""); setDateTo(""); }}>
            {s.icon} {s.label}
          </button>
        ))}
      </div>

      {/* Filters */}
      <div className="card" style={{ padding: "16px 20px" }}>
        <div style={{ display: "flex", gap: 12, flexWrap: "wrap", alignItems: "flex-end" }}>
          <div className="field" style={{ flex: 2, minWidth: 180 }}>
            <label>🔍 Search</label>
            <input value={search} onChange={e => setSearch(e.target.value)} placeholder="Name, cheque no, category…" />
          </div>
          <div className="field" style={{ minWidth: 140 }}>
            <label>From Date</label>
            <input type="date" value={dateFrom} onChange={e => setDateFrom(e.target.value)} />
          </div>
          <div className="field" style={{ minWidth: 140 }}>
            <label>To Date</label>
            <input type="date" value={dateTo} onChange={e => setDateTo(e.target.value)} />
          </div>
          <button className="btn btn-secondary" onClick={() => { setSearch(""); setDateFrom(""); setDateTo(""); }}>Clear</button>
          <button className="btn btn-secondary" onClick={() => loadRecords()} disabled={loading}>
            {loading ? <><span className="spinner" style={{ borderTopColor: "#3D4F56", borderColor: "#ccc" }} /> Loading</> : "🔄 Refresh"}
          </button>
          {filtered.length > 0 && (
            <button className="btn btn-secondary" onClick={downloadCSV}>⬇️ CSV</button>
          )}
        </div>
      </div>

      {/* Stats bar */}
      {filtered.length > 0 && (
        <div style={{ display: "flex", gap: 16, marginBottom: 14, flexWrap: "wrap" }}>
          <div style={{ fontSize: 13, color: "#7A9199" }}>
            Showing <strong style={{ color: "#1A4D5C" }}>{filtered.length}</strong> of {rows.length} records
          </div>
          {totalAmount > 0 && (
            <div style={{ fontSize: 13, color: "#7A9199" }}>
              Total Amount: <strong style={{ color: "#1A4D5C" }}>₹{totalAmount.toLocaleString("en-IN", { minimumFractionDigits: 2 })}</strong>
            </div>
          )}
        </div>
      )}

      {/* Data Table */}
      <div className="card" style={{ padding: "0", overflow: "hidden" }}>
        {loading
          ? <div style={{ padding: 40, textAlign: "center", color: "#7A9199" }}>
              <div style={{ fontSize: 32, marginBottom: 10 }}>⏳</div>
              Loading records…
            </div>
          : filtered.length === 0
          ? <div style={{ padding: 30, textAlign: "center" }}>
              <div style={{ fontSize: 32, marginBottom: 8 }}>📭</div>
              <div style={{ color: "#7A9199", fontSize: 14 }}>No records match your filters.</div>
            </div>
          : <div style={{ overflowX: "auto" }}>
              <table className="records-table">
                <thead>
                  <tr>{headers.map((h, i) => <th key={i}>{h}</th>)}</tr>
                </thead>
                <tbody>
                  {filtered.map((row, ri) => (
                    <tr key={ri}>
                      {headers.map((h, ci) => {
                        const val = row[ci] || "";
                        const isLink = val.startsWith("http");
                        const isAmt  = h.toLowerCase() === "amount";
                        const isMode = h === "Payment Mode";
                        return (
                          <td key={ci} style={{ fontSize: 12, maxWidth: 180, overflow: "hidden", textOverflow: "ellipsis", whiteSpace: "nowrap" }}>
                            {isLink
                              ? <a href={val} target="_blank" rel="noreferrer" style={{ color: "#3A8FA3", textDecoration: "underline" }}>🔗 View</a>
                              : isAmt
                              ? <strong>₹{Number(val).toLocaleString("en-IN")}</strong>
                              : isMode
                              ? <span className={`tag tag-${val === "Cheque" ? "cheque" : "cash"}`}>{val}</span>
                              : val || "—"
                            }
                          </td>
                        );
                      })}
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
        }
      </div>
    </div>
  );
}

// ─── MAIN APP ─────────────────────────────────────────────────────────────────
// Setup tab hidden from nav — accessible only when needed via setTab("setup")
// public:true tabs are visible to all visitors without sign-in
const TABS = [
{ id:"setup",      label:"Setup",        icon:"⚙️", public:false },    
{ id:"members",    label:"Committee",    icon:"👥", public:false },
  { id:"cheque",     label:"Cheques",      icon:"🏦", public:false },
  { id:"withdrawal", label:"Cash Out",     icon:"💵", public:false },
  { id:"expense",    label:"Expenses",     icon:"📊", public:false },
  { id:"petty",      label:"Cash Tracker", icon:"⚖️", public:true  },
  { id:"settle",     label:"Settlements",  icon:"🤝", public:false },
  { id:"records",    label:"View Records", icon:"📁", public:true  },
];

export default function App() {
  const [tab, setTab] = useState("members");
  const [token, setToken] = useState(null);
  const [currentUser, setCurrentUser] = useState("");
  const [members, setMembers] = useState([]);
  const [authLoading, setAuthLoading] = useState(false);

  useEffect(() => {
    const s = document.createElement("script");
    s.src = "https://accounts.google.com/gsi/client";
    s.async = true;
    document.head.appendChild(s);
    return () => { try { document.head.removeChild(s); } catch(e){} };
  }, []);

  function signIn() {
    if (!window.google) { alert("Google SDK loading… please try again in a moment."); return; }
    setAuthLoading(true);
    const client = window.google.accounts.oauth2.initTokenClient({
      client_id: CONFIG.CLIENT_ID,
      scope: CONFIG.SCOPES,
      callback: async (resp) => {
        if (resp.error) { setAuthLoading(false); return; }
        setToken(resp.access_token);
        try {
          const r = await fetch("https://www.googleapis.com/oauth2/v3/userinfo", { headers: { Authorization: `Bearer ${resp.access_token}` } });
          const u = await r.json();
          setCurrentUser(u.name || u.email || "User");
          const rows = await readSheet(SHEETS.MEMBERS, resp.access_token);
          setMembers(rows);
        } catch(e){}
        setAuthLoading(false);
      },
    });
    client.requestAccessToken();
  }

  function signOut() { setToken(null); setCurrentUser(""); setMembers([]); }

  const isConfigured = CONFIG.SPREADSHEET_ID !== "YOUR_SPREADSHEET_ID_HERE";
  const refreshMembers = (t = token) => readSheet(SHEETS.MEMBERS, t).then(setMembers).catch(()=>{});

  return (
    <>
      <style>{globalCSS}</style>
      <header className="portal-header">
        <div className="header-top">
          <div className="header-logo">🏢</div>
          <div>
            <div className="header-title">Shubh Nisarg CHS Ltd</div>
            <div className="header-sub">Society Management Portal · Badlapur, Thane, Maharashtra</div>
          </div>
          <div className="header-auth">
            {token
              ? <>
                  <span className="auth-badge">👤 {currentUser}</span>
                  <button className="btn-auth" onClick={signOut}>Sign Out</button>
                </>
              : <button className="btn-auth" onClick={signIn} disabled={authLoading || !isConfigured}>
                  {authLoading ? "Signing in…" : "🔐 Sign in with Google"}
                </button>
            }
          </div>
        </div>
        <nav className="nav-tabs">
          {TABS.map(t => (
            <button key={t.id}
              className={`nav-tab ${tab === t.id ? "active" : ""} ${!token && !t.public ? "nav-tab-locked" : ""}`}
              onClick={() => setTab(t.id)}
              title={!token && !t.public ? "Sign in required" : ""}>
              {t.icon} {t.label}
              {t.public && <span className="tab-public-badge">Public</span>}
            </button>
          ))}
        </nav>
      </header>

      <main className="page">
        {/* Show sign-in prompt only on protected tabs when not signed in */}
        {!token && TABS.find(t => t.id === tab && !t.public) && (
          <div style={{ background:"#fff", borderRadius:14, padding:"40px 24px", textAlign:"center", boxShadow:"0 2px 8px rgba(26,77,92,0.08)", marginBottom:20 }}>
            <div style={{ fontSize:48, marginBottom:16 }}>🔐</div>
            <div style={{ fontFamily:"'Poppins',sans-serif", fontSize:20, fontWeight:700, color:"#1A4D5C", marginBottom:8 }}>
              Sign In Required
            </div>
            <div style={{ fontSize:14, color:"#7A9199", marginBottom:24, maxWidth:380, margin:"0 auto 24px" }}>
              This section is restricted to authorised committee members only.
              Please sign in with your Google account to continue.
            </div>
            <button className="btn btn-primary" onClick={signIn} disabled={authLoading}
              style={{ fontSize:15, padding:"12px 32px", margin:"0 auto" }}>
              {authLoading ? <><span className="spinner" /> Signing in…</> : "🔐 Sign in with Google"}
            </button>
            <div style={{ marginTop:16, fontSize:12, color:"#7A9199" }}>
              Only authorised accounts can access this section.
              <br />You can still view the <strong>Cash Tracker</strong> and <strong>View Records</strong> tabs without signing in.
            </div>
          </div>
        )}
        {tab === "setup"      && <SetupGuide token={token} onHeadersWritten={() => refreshMembers()} />}
        {tab === "members"    && token && <MembersTab token={token} members={members} onRefresh={refreshMembers} currentUser={currentUser} />}
        {tab === "cheque"     && token && <ChequePayment token={token} currentUser={currentUser} />}
        {tab === "withdrawal" && token && <CashWithdrawal token={token} members={members} currentUser={currentUser} />}
        {tab === "expense"    && token && <ExpenseTracker token={token} members={members} currentUser={currentUser} />}
        {tab === "petty"      && <PettyCashTracker token={token} members={members} currentUser={currentUser} onSignIn={signIn} />}
        {tab === "settle"     && token && <SettlementTab token={token} members={members} currentUser={currentUser} />}
        {tab === "records"    && <ViewRecords token={token} onSignIn={signIn} />}
      </main>
    </>
  );
}
