function generateRefId() { return "REF-" + Date.now().toString(36).toUpperCase(); }
function today() { return new Date().toISOString().split("T")[0]; }
function nowTs() { return new Date().toLocaleString("en-IN", { timeZone: "Asia/Kolkata" }); }

function compressImage(file, maxW = 800, quality = 0.55) {
  return new Promise((resolve) => {
    const reader = new FileReader();
    reader.onload = (e) => {
      const img = new Image();
      img.onload = () => {
        const canvas = document.createElement("canvas");
        let w = img.width, h = img.height;
        if (w > maxW) { h = (h * maxW) / w; w = maxW; }
        canvas.width = w; canvas.height = h;
        canvas.getContext("2d").drawImage(img, 0, 0, w, h);
        canvas.toBlob((blob) => resolve(blob), "image/jpeg", quality);
      };
      img.src = e.target.result;
    };
    reader.readAsDataURL(file);
  });
}

// ─── GOOGLE API HELPERS ───────────────────────────────────────────────────────
async function appendToSheet(sheetName, rowData, token) {
  const url = `https://sheets.googleapis.com/v4/spreadsheets/${CONFIG.SPREADSHEET_ID}/values/${encodeURIComponent(sheetName + "!A1")}:append?valueInputOption=USER_ENTERED&insertDataOption=INSERT_ROWS`;
  const resp = await fetch(url, {
    method: "POST",
    headers: { Authorization: `Bearer ${token}`, "Content-Type": "application/json" },
    body: JSON.stringify({ values: [rowData] }),
  });
  if (!resp.ok) throw new Error(await resp.text());
  return resp.json();
}

// Update a specific row in a sheet (1-indexed, row 1 = header, row 2 = first data row)
async function updateSheetRow(sheetName, rowIndex, rowData, token) {
  // rowIndex is 1-based data row index (1 = first data row = sheet row 2)
  const sheetRow = rowIndex + 1; // +1 because row 1 is header
  const url = `https://sheets.googleapis.com/v4/spreadsheets/${CONFIG.SPREADSHEET_ID}/values/${encodeURIComponent(sheetName + "!A" + sheetRow)}?valueInputOption=USER_ENTERED`;
  const resp = await fetch(url, {
    method: "PUT",
    headers: { Authorization: `Bearer ${token}`, "Content-Type": "application/json" },
    body: JSON.stringify({ values: [rowData] }),
  });
  if (!resp.ok) throw new Error(await resp.text());
  return resp.json();
}

// Get total row count in a sheet (to find last row index)
async function getLastRowIndex(sheetName, token) {
  const rows = await readSheet(sheetName, token);
  return rows.length; // 1-based index of last data row
}

async function readSheet(sheetName, token) {
  const url = `https://sheets.googleapis.com/v4/spreadsheets/${CONFIG.SPREADSHEET_ID}/values/${encodeURIComponent(sheetName + "!A2:Z500")}`;
  const resp = await fetch(url, { headers: { Authorization: `Bearer ${token}` } });
  if (!resp.ok) throw new Error(await resp.text());
  const data = await resp.json();
  return data.values || [];
}

async function writeSheetHeaders(sheetName, headers, token) {
  const url = `https://sheets.googleapis.com/v4/spreadsheets/${CONFIG.SPREADSHEET_ID}/values/${encodeURIComponent(sheetName + "!A1")}?valueInputOption=RAW`;
  const resp = await fetch(url, {
    method: "PUT",
    headers: { Authorization: `Bearer ${token}`, "Content-Type": "application/json" },
    body: JSON.stringify({ values: [headers] }),
  });
  if (!resp.ok) throw new Error(await resp.text());
  return resp.json();
}

async function uploadToDrive(blob, fileName, token) {
  const meta = JSON.stringify({ name: fileName, parents: [CONFIG.DRIVE_FOLDER_ID] });
  const form = new FormData();
  form.append("metadata", new Blob([meta], { type: "application/json" }));
  form.append("file", blob, fileName);
  const resp = await fetch("https://www.googleapis.com/upload/drive/v3/files?uploadType=multipart&fields=id,webViewLink", {
    method: "POST",
    headers: { Authorization: `Bearer ${token}` },
    body: form,
  });
  if (!resp.ok) throw new Error(await resp.text());
  const data = await resp.json();
  await fetch(`https://www.googleapis.com/drive/v3/files/${data.id}/permissions`, {
    method: "POST",
    headers: { Authorization: `Bearer ${token}`, "Content-Type": "application/json" },
    body: JSON.stringify({ role: "reader", type: "anyone" }),
  });
  return data.webViewLink;
}

